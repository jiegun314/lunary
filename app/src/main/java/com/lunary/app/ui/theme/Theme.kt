/**
 * Material 3 / Material You theme.
 *
 * Android 12+ uses the wallpaper-derived palette when dynamic colour is on;
 * otherwise (and on older devices) the static Lunary purple palette is used.
 */
@Composable
fun LunaryTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> LunaryDarkColors
        else -> LunaryLightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = LunaryTypography,
        shapes = LunaryShapes,
        content = content
    )
}
